import json
import time
from datetime import date, timedelta
from pathlib import Path

import numpy as np
import pandas as pd
from sqlalchemy import text

from app.db import engine
from forecast.models import MODELS, mae, wape

SOURCE = "online_retail"
HORIZON = 28
STEP = 7
BACKTEST_DAYS = 182
TOP_N = 50
DOCS_DIR = Path(__file__).resolve().parents[2] / "docs"


def make_cutoffs(
    first: date, last_data_day: date, horizon: int, step: int
) -> list[date]:
    """Cutoffs from `first`, every `step` days, while a full horizon still fits in the data."""
    cutoffs = []
    cutoff = first
    while cutoff + timedelta(days=horizon) <= last_data_day:
        cutoffs.append(cutoff)
        cutoff += timedelta(days=step)
    return cutoffs


def backtest_series(
    series: pd.Series, cutoffs: list[date], horizon: int
) -> pd.DataFrame:
    """Expanding-window backtest of every model on one daily series (indexed by date).

    Each fold trains on all days up to and including the cutoff and forecasts
    the next `horizon` days, so no future sales leak into training.
    """
    rows = []
    for cutoff in cutoffs:
        history = series[series.index <= cutoff].to_numpy()
        actual = series[
            (series.index > cutoff) & (series.index <= cutoff + timedelta(days=horizon))
        ]
        for model_name, model in MODELS.items():
            predicted = model(history, horizon)
            for horizon_date, a, p in zip(actual.index, actual.to_numpy(), predicted):
                rows.append(
                    {
                        "cutoff": cutoff,
                        "horizon_date": horizon_date,
                        "model": model_name,
                        "actual": float(a),
                        "predicted": float(p),
                    }
                )
    return pd.DataFrame(rows)


def summarize(results: pd.DataFrame) -> pd.DataFrame:
    """Pooled WAPE and MAE per model across all products and folds."""
    return (
        results.groupby("model")
        .apply(
            lambda g: pd.Series(
                {
                    "wape": wape(g["actual"].to_numpy(), g["predicted"].to_numpy()),
                    "mae": mae(g["actual"].to_numpy(), g["predicted"].to_numpy()),
                }
            ),
            include_groups=False,
        )
        .sort_values("wape")
    )


def load_daily_sales() -> pd.DataFrame:
    with engine.begin() as conn:
        rows = conn.execute(
            text(
                "SELECT product_id, sale_date, quantity_sold, revenue "
                "FROM daily_sales WHERE source = :source"
            ),
            {"source": SOURCE},
        ).all()
    df = pd.DataFrame(
        rows, columns=["product_id", "sale_date", "quantity_sold", "revenue"]
    )
    df["revenue"] = df["revenue"].astype(float)
    return df


def full_series(product_sales: pd.DataFrame, last_data_day: date) -> pd.Series:
    """Daily quantity from the product's first sale to the last data day; days after
    its last sale are zero (nothing sold), the partial final day is dropped."""
    s = product_sales.set_index("sale_date")["quantity_sold"].astype(float)
    s = s[s.index <= last_data_day]
    full_range = pd.date_range(s.index.min(), last_data_day, freq="D").date
    return s.reindex(full_range, fill_value=0.0)


def write_report(summary: pd.DataFrame, meta: dict) -> None:
    DOCS_DIR.mkdir(exist_ok=True)
    lines = [
        "# Backtest results",
        "",
        "Rolling-origin (expanding window) backtest on Online Retail II daily unit sales.",
        "Generated by `python -m forecast.backtest`. Only numbers from this file should be reported.",
        "",
        "| Setting | Value |",
        "|---|---|",
        f"| Products | top {meta['n_products']} by revenue before the first cutoff |",
        f"| Folds | {meta['n_folds']} (cutoff every {STEP} days) |",
        f"| Horizon | {HORIZON} days |",
        f"| Cutoffs | {meta['first_cutoff']} to {meta['last_cutoff']} |",
        f"| Evaluated days | {meta['first_eval_day']} to {meta['last_eval_day']} |",
        f"| Forecast points per model | {meta['n_points']:,} |",
        "",
        "| Model | WAPE | MAE (units/day) |",
        "|---|---|---|",
    ]
    for model_name, row in summary.iterrows():
        lines.append(f"| {model_name} | {row['wape']:.1%} | {row['mae']:.2f} |")
    lines += [
        "",
        "Notes:",
        (
            "- WAPE = sum of |error| / sum of actual units, pooled over all products and folds. "
            "MAPE isn't used because most product-days have zero sales."
        ),
        "- Ranking products by revenue before the first cutoff keeps future sales out of product selection.",
        f"- {meta['dropped_day']} is excluded: the data ends mid-day, so it's a partial day.",
        "- Saturdays have almost no orders in this dataset, so weekly patterns matter.",
        "- Large wholesale orders cause spikes; they are kept, not clipped.",
        "",
    ]
    (DOCS_DIR / "backtest_results.md").write_text("\n".join(lines), encoding="utf-8")
    payload = {**meta, "models": summary.reset_index().to_dict(orient="records")}
    (DOCS_DIR / "backtest_results.json").write_text(
        json.dumps(payload, indent=2), encoding="utf-8"
    )


def save_forecasts(
    best_results: pd.DataFrame, future: pd.DataFrame, model_name: str
) -> int:
    records = [
        {
            "product_id": int(r.product_id),
            "source": SOURCE,
            "forecast_made_date": r.cutoff,
            "horizon_date": r.horizon_date,
            "predicted_quantity": round(float(r.predicted), 2),
            "model_name": model_name,
        }
        for r in pd.concat([best_results, future]).itertuples(index=False)
    ]
    with engine.begin() as conn:
        conn.execute(
            text("DELETE FROM forecasts WHERE source = :source"), {"source": SOURCE}
        )
        conn.execute(
            text(
                "INSERT INTO forecasts (product_id, source, forecast_made_date, horizon_date, "
                "predicted_quantity, model_name) VALUES (:product_id, :source, "
                ":forecast_made_date, :horizon_date, :predicted_quantity, :model_name)"
            ),
            records,
        )
    return len(records)


def main() -> None:
    t0 = time.time()
    sales = load_daily_sales()
    dropped_day = sales["sale_date"].max()
    last_data_day = dropped_day - timedelta(days=1)
    first_cutoff = last_data_day - timedelta(days=BACKTEST_DAYS)
    cutoffs = make_cutoffs(first_cutoff, last_data_day, HORIZON, STEP)

    before = sales[sales["sale_date"] <= first_cutoff]
    top_ids = before.groupby("product_id")["revenue"].sum().nlargest(TOP_N).index

    all_results = []
    for product_id in top_ids:
        series = full_series(sales[sales["product_id"] == product_id], last_data_day)
        result = backtest_series(series, cutoffs, HORIZON)
        result["product_id"] = product_id
        all_results.append(result)
    results = pd.concat(all_results, ignore_index=True)

    summary = summarize(results)
    best_model = summary.index[0]
    print(summary.to_string())

    future_rows = []
    for product_id in top_ids:
        series = full_series(sales[sales["product_id"] == product_id], last_data_day)
        predicted = MODELS[best_model](series.to_numpy(), HORIZON)
        for i, p in enumerate(predicted, start=1):
            future_rows.append(
                {
                    "cutoff": last_data_day,
                    "horizon_date": last_data_day + timedelta(days=i),
                    "model": best_model,
                    "actual": np.nan,
                    "predicted": p,
                    "product_id": product_id,
                }
            )
    future = pd.DataFrame(future_rows)

    best = results[results["model"] == best_model]
    meta = {
        "n_products": len(top_ids),
        "n_folds": len(cutoffs),
        "horizon_days": HORIZON,
        "first_cutoff": str(cutoffs[0]),
        "last_cutoff": str(cutoffs[-1]),
        "first_eval_day": str(results["horizon_date"].min()),
        "last_eval_day": str(results["horizon_date"].max()),
        "n_points": len(best),
        "dropped_day": str(dropped_day),
        "best_model": best_model,
        "product_ids": [int(p) for p in top_ids],
    }
    write_report(summary, meta)
    n_saved = save_forecasts(best, future, best_model)
    print(f"best model: {best_model}; saved {n_saved:,} forecast rows")
    print(f"wrote {DOCS_DIR / 'backtest_results.md'} in {time.time() - t0:.1f}s")


if __name__ == "__main__":
    main()
